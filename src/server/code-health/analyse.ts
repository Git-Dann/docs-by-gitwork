import { lstat, readFile } from "node:fs/promises";
import { join } from "node:path";
import { isExampleOrFixturePath, isVendoredPath } from "@/server/pulse-checks/native-mobile";
import { parseWithBudget, parserFor } from "./grammar";
import { EXTENSION_LANGUAGE, LANGUAGE_RULES, UNSUPPORTED_SOURCE_EXTENSIONS } from "./languages";
import { measureTree, type MeasureNode } from "./measure";
import { bandOf, buildRegister, HOURS_PER_DAY, scoreOf } from "./rules";
import type { CodeHealthReport, CodeHistory, CodeLanguage, FileMeasure, LanguageSummary } from "@/types/code-health";

/** Files larger than this are almost always generated or bundled, not written. */
export const MAX_FILE_BYTES = 256 * 1024;
/** Measuring stops here, and the report says it stopped. */
export const MAX_FILES = 6_000;
/** Whole-run budget. A repo that takes longer is reported as partially measured. */
const TIME_BUDGET_MS = 60_000;

const BUILD_OUTPUT = /(^|\/)(docs?|site|\.github|dist|build|out|\.next|\.nuxt|\.svelte-kit|coverage|target|bin|obj|generated|__generated__|gen)\//i;
const GENERATED_NAME = /(\.min\.(js|mjs|cjs)|\.d\.ts|\.bundle\.js|\.pb\.go|_pb2\.py|\.g\.dart|\.generated\.\w+|-lock\.\w+)$/i;
const GENERATED_BANNER = /@generated|DO NOT EDIT|auto-?generated|Code generated by/i;
const TEST_PATH = /(^|\/)(__tests__|tests?|spec|specs|e2e|androidTest|UITests?|Tests)\/|[._-](test|spec)\.\w+$|_test\.go$|Tests?\.(swift|kt|java)$|(^|\/)test_[^/]+\.py$/i;

export type SkipReason = "generated" | "large" | "minified" | "unsupported" | "excluded";

/** What to do with a tracked path, decided from the path alone. */
export function classifyPath(path: string): { language: CodeLanguage; isTest: boolean } | { skip: SkipReason; label?: string } {
  if (isVendoredPath(path) || BUILD_OUTPUT.test(path)) return { skip: "excluded" };
  if (GENERATED_NAME.test(path)) return { skip: "generated" };
  const dot = path.lastIndexOf(".");
  const ext = dot >= 0 ? path.slice(dot).toLowerCase() : "";
  const language = EXTENSION_LANGUAGE[ext];
  if (!language) {
    const label = UNSUPPORTED_SOURCE_EXTENSIONS[ext];
    return label && !isExampleOrFixturePath(path) ? { skip: "unsupported", label } : { skip: "excluded" };
  }
  const isTest = TEST_PATH.test(path);
  // Examples and fixtures are not the product. Tests are kept (counted separately).
  if (!isTest && isExampleOrFixturePath(path)) return { skip: "excluded" };
  return { language, isTest };
}

/** Minified or generated by content: very long average lines, or a generator banner up top. */
export function looksGenerated(source: string): "minified" | "generated" | null {
  if (GENERATED_BANNER.test(source.slice(0, 600))) return "generated";
  const lines = source.split("\n");
  const avg = source.length / Math.max(1, lines.length);
  if (avg > 300 || (lines.length < 5 && source.length > 5_000)) return "minified";
  return null;
}

export interface AnalyseInput {
  repo: string;
  branch: string | null;
  commit: string | null;
  dir: string;
  files: string[];
  /** For tests. */
  now?: () => number;
}

/** The parsed files, for the history pass, which needs per-file complexity. */
export interface Analysed {
  report: CodeHealthReport;
  measured: FileMeasure[];
}

export async function analyseCheckout(input: AnalyseInput): Promise<Analysed> {
  const now = input.now ?? Date.now;
  const started = now();
  const coverage: CodeHealthReport["coverage"] = {
    analysedFiles: 0,
    skippedLarge: 0,
    skippedMinified: 0,
    skippedGenerated: 0,
    unsupportedSourceFiles: 0,
    unsupportedLanguages: [],
    filesWithParseErrors: 0,
    truncated: false,
  };
  const unsupported = new Set<string>();
  const measured: FileMeasure[] = [];
  const parsers = new Map<CodeLanguage, Awaited<ReturnType<typeof parserFor>>>();

  try {
    for (const path of [...input.files].sort()) {
      const c = classifyPath(path);
      if ("skip" in c) {
        if (c.skip === "generated") coverage.skippedGenerated++;
        if (c.skip === "unsupported") {
          coverage.unsupportedSourceFiles++;
          if (c.label) unsupported.add(c.label);
        }
        continue;
      }
      if (measured.length >= MAX_FILES || now() - started > TIME_BUDGET_MS) {
        coverage.truncated = true;
        break;
      }
      const abs = join(input.dir, path);
      const st = await lstat(abs).catch(() => null);
      if (!st || !st.isFile()) continue; // symlinks, submodules, anything that is not a plain file
      if (st.size > MAX_FILE_BYTES) {
        coverage.skippedLarge++;
        continue;
      }
      const source = await readFile(abs, "utf8").catch(() => null);
      if (source === null) continue;
      const gen = looksGenerated(source);
      if (gen === "minified") {
        coverage.skippedMinified++;
        continue;
      }
      if (gen === "generated") {
        coverage.skippedGenerated++;
        continue;
      }

      let parser = parsers.get(c.language);
      if (!parser) {
        parser = await parserFor(c.language);
        parsers.set(c.language, parser);
      }
      const tree = parseWithBudget(parser, source);
      if (!tree) continue; // parse timed out: skip the file rather than stall the scan
      try {
        const root = tree.rootNode as unknown as MeasureNode & { hasError: boolean | (() => boolean) };
        const hasError = typeof root.hasError === "function" ? root.hasError() : root.hasError;
        const m = measureTree(root, LANGUAGE_RULES[c.language], source.split("\n").length);
        if (hasError) coverage.filesWithParseErrors++;
        measured.push({ path, language: c.language, loc: m.loc, isTest: c.isTest, functions: m.functions, classes: m.classes, parseErrors: !!hasError });
        coverage.analysedFiles++;
      } finally {
        tree.delete();
      }
    }
  } finally {
    for (const p of parsers.values()) p.delete();
  }

  coverage.unsupportedLanguages = [...unsupported].sort();
  return { report: buildReport(input, measured, coverage, now), measured };
}

/** Pure: measures in, report out. Split out so it can be tested without a parser. */
export function buildReport(
  input: Pick<AnalyseInput, "repo" | "branch" | "commit">,
  measured: FileMeasure[],
  coverage: CodeHealthReport["coverage"],
  now: () => number = Date.now,
  history: CodeHistory | null = null,
): CodeHealthReport {
  const prod = measured.filter((f) => !f.isTest);
  const loc = prod.reduce((s, f) => s + f.loc, 0);
  const testLoc = measured.filter((f) => f.isTest).reduce((s, f) => s + f.loc, 0);
  const fns = prod.flatMap((f) => f.functions);
  const totalComplexity = fns.reduce((s, f) => s + f.complexity, 0);
  const { score, complexLocShare } = scoreOf(measured);
  const { debt, counts, effortHours } = buildRegister(measured);

  const byLang = new Map<CodeLanguage, LanguageSummary>();
  for (const f of prod) {
    const l = byLang.get(f.language) ?? { language: f.language, files: 0, loc: 0 };
    l.files++;
    l.loc += f.loc;
    byLang.set(f.language, l);
  }

  return {
    repo: input.repo,
    branch: input.branch,
    commit: input.commit,
    measuredAt: new Date(now()).toISOString(),
    score,
    band: bandOf(score),
    totals: {
      files: prod.length,
      loc,
      testLoc,
      functions: fns.length,
      classes: prod.reduce((s, f) => s + f.classes.length, 0),
      complexityPerKloc: loc ? Math.round((totalComplexity / loc) * 1000 * 10) / 10 : 0,
      complexLocShare: Math.round(complexLocShare * 1000) / 1000,
      averageComplexity: fns.length ? Math.round((totalComplexity / fns.length) * 10) / 10 : 0,
    },
    languages: [...byLang.values()].sort((a, b) => b.loc - a.loc),
    debt,
    debtCounts: counts,
    effort: { hours: effortHours, days: Math.round((effortHours / HOURS_PER_DAY) * 10) / 10 },
    history,
    coverage,
  };
}
